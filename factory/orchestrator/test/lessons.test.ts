let seq = 0;

function ev(partial: Partial<EventRecord> & { event_type: string }): StoredEvent {
  seq += 1;
  const record: EventRecord = {
    ts: partial.ts ?? '2026-08-01T00:00:00.000Z',
    session_id: 'sess-dream',
    actor: partial.actor ?? 'system',
    event_type: partial.event_type,
    task_id: partial.task_id,
    plan_version: partial.plan_version ?? 1,
    causal_parent: partial.causal_parent ?? null,
    payload: partial.payload ?? {},
  };
  return { event_id: `sess-dream#${seq}`, record };
}

describe('shingles / jaccardSimilarity', () => {
  it('shingles a short phrase (<= size words) as a single shingle', () => {
    expect(shingles('never edit lockfiles', 3)).toEqual(new Set(['never edit lockfiles']));
  });

  it('normalizes case and punctuation before shingling', () => {
    const a = shingles('Never edit lockfiles in workers!', 3);
    const b = shingles('never   edit lockfiles in workers', 3);
    expect(a).toEqual(b);
  });

  it('identical texts have similarity 1', () => {
    const s = shingles('always check the upper loop bound against array length');
    expect(jaccardSimilarity(s, s)).toBe(1);
  });

  it('unrelated texts have low similarity', () => {
    const a = shingles('always check the upper loop bound against array length');
    const b = shingles('lockfiles are regenerable and never hand-edited by a worker');
    expect(jaccardSimilarity(a, b)).toBeLessThan(0.2);
  });
});

describe('checkNovelty', () => {
  const existing = [
    'Always check the upper loop bound against array length, not a hardcoded value.',
    'Lockfiles are regenerable and regenerated by the merge queue.',
  ];

  it('flags a near-identical restatement (trivial punctuation/casing drift) as not novel', () => {
    const result = checkNovelty(
      'always check the upper loop bound against array length, not a hardcoded value',
      existing,
      0.8,
    );
    expect(result.novel).toBe(false);
    expect(result.mostSimilar?.statement).toBe(existing[0]);
  });

  it('flags a genuinely new statement as novel', () => {
    const result = checkNovelty(
      'Cloudflare D1 does not support multi-statement transactions across workers.',
      existing,
      0.8,
    );
    expect(result.novel).toBe(true);
  });

  it('treats an empty existing corpus as trivially novel', () => {
    expect(checkNovelty('anything at all', [], 0.8).novel).toBe(true);
  });

  it('boundary: a score exactly equal to the threshold is treated as redundant, not novel', () => {
    const statement = 'x y z';
    // Two shingle sets whose Jaccard similarity is exactly 1 (identical text).
    const result = checkNovelty(statement, [statement], 1);
    expect(jaccardSimilarity(shingles(statement), shingles(statement))).toBe(1);
    expect(result.mostSimilar?.score).toBe(1);
    expect(result.novel).toBe(false); // score (1) === threshold (1) -> not novel
    expect(result.polarityConflict).toBe(false);
  });

  it('does NOT auto-reject a near-duplicate whose polarity contradicts the nearest match — surfaces as novel with polarityConflict', () => {
    const priorLessons = [
      'Always retry the request automatically on a network timeout before giving up.',
    ];
    const result = checkNovelty(
      'Never retry the request automatically on a network timeout before giving up.',
      priorLessons,
      0.8,
    );
    // High textual similarity (would normally auto-novelty-reject)...
    expect(result.mostSimilar?.score).toBeGreaterThanOrEqual(0.8);
    // ...but the "always" vs "never" polarity flip must keep it novel instead
    // of silently discarding a genuine contradiction (architecture §9.6).
    expect(result.polarityConflict).toBe(true);
    expect(result.novel).toBe(true);
  });

  it('does not flag polarityConflict when neither statement carries a polarity marker, even at high similarity', () => {
    const result = checkNovelty(
      'Retry the request automatically on a network timeout before giving up.',
      ['Retry the request automatically on a network timeout before giving in.'],
      0.5,
    );
    expect(result.mostSimilar?.score).toBeGreaterThanOrEqual(0.5);
    expect(result.polarityConflict).toBe(false);
    expect(result.novel).toBe(false);
  });

  it('reads two spellings of the same prohibition as one lesson, not a contradiction', () => {
    // The guard is documented as comparing polarity "vs their absence" -- what
    // the two statements assert, not which words they assert it with. English
    // spells a prohibition several ways, and the marker list holds four of
    // them, so a candidate that says "must not" against a corpus that says
    // "do not" shares no marker with its own near-duplicate. That is the
    // redundant candidate this gate exists to reject, and calling it a
    // contradiction does not merely let it through: `contradiction_of` is
    // written onto the lesson-candidate-raised event and the UI warns that the
    // two rules disagree in memory. Both statements forbid the same thing.
    const result = checkNovelty(
      'Agents must not echo credential values into the event log or a PR body.',
      ['Agents do not echo credential values into the event log or a PR body.'],
      0.7,
    );
    expect(result.mostSimilar?.score).toBeGreaterThanOrEqual(0.7);
    expect(result.polarityConflict).toBe(false);
    expect(result.novel).toBe(false);
  });

  it('reads an intensifier as the same instruction, not its opposite', () => {
    // "always X" and a bare "X" both tell you to do X. The guard compares
    // polarity against absence, and absence of a PROHIBITION is an opposition
    // -- absence of an intensifier is not, it is the same instruction said
    // with less force. Left as a difference, every near-duplicate that merely
    // dropped the "always" was called a contradiction of the rule it restates,
    // escaped the redundancy gate it should have been caught by, and had
    // `contradiction_of` written onto its lesson-candidate-raised event.
    const result = checkNovelty(
      'Always retry the request automatically on a network timeout before giving up.',
      ['Retry the request automatically on a network timeout before giving up.'],
      0.8,
    );
    expect(result.mostSimilar?.score).toBeGreaterThanOrEqual(0.8);
    expect(result.polarityConflict).toBe(false);
    expect(result.novel).toBe(false);
  });

  it('still reads a bare statement as the opposite of the prohibition of it', () => {
    // The other half of "vs their absence", and the half that is real: this is
    // the row that fails if the fix above is taken as "absence never differs".
    const result = checkNovelty(
      'Never retry the request automatically on a network timeout before giving up.',
      ['Retry the request automatically on a network timeout before giving up.'],
      0.8,
    );
    expect(result.mostSimilar?.score).toBeGreaterThanOrEqual(0.8);
    expect(result.polarityConflict).toBe(true);
    expect(result.novel).toBe(true);
  });
});

describe('length-aware novelty (P9-35 (a))', () => {
  // A statement without polarity markers, so these tests exercise the length
  // rule alone and not the contradiction escape hatch that sits behind it.
  const RULE = 'check the upper loop bound against the array length rather than a hardcoded value';
  const ONE_EDIT = RULE.replace('bound', 'limit');
  const CONTAINED = 'check the upper loop bound against the array length';

  describe('oneWordEditCeiling', () => {
    it('is blind below 2s+1 words, where one edit and a coincidence look the same', () => {
      // At six words the two statements still share exactly one trigram after
      // an edit -- and so do two unrelated statements that happen to repeat a
      // three-word run. No bar separates those, so the caller keeps its own.
      for (const words of [0, 1, 3, 5, 6]) expect(oneWordEditCeiling(words)).toBeNull();
      expect(oneWordEditCeiling(7)).toBeCloseTo(0.25, 10);
    });

    it('is the arithmetic it claims: (n - 2s + 1) / (n + 1)', () => {
      for (const n of [7, 10, 14, 20, 29, 40]) {
        expect(oneWordEditCeiling(n)).toBeCloseTo((n - 5) / (n + 1), 10);
      }
      // The number that makes the point: the fixed 0.8 bar only starts
      // catching one-word edits at twenty-nine words. Every shorter lesson --
      // which is most of them -- had a free pass.
      expect(oneWordEditCeiling(29)).toBeCloseTo(0.8, 10);
    });

    it('is a score the real shingler produces, not a derivation nobody checked', () => {
      const words = Array.from({ length: 14 }, (_, i) => `w${i}`);
      const original = words.join(' ');
      const edited = words.map((w, i) => (i === 7 ? 'zz' : w)).join(' ');
      expect(jaccardSimilarity(shingles(original), shingles(edited))).toBeCloseTo(
        oneWordEditCeiling(14) as number,
        10,
      );
    });

    it('tracks the shingle size it is given rather than assuming three', () => {
      expect(oneWordEditCeiling(8, 4)).toBeNull(); // 2*4 + 1 = 9
      expect(oneWordEditCeiling(9, 4)).toBeCloseTo(0.2, 10);
    });
  });

  describe('effectiveNoveltyThreshold', () => {
    it('lowers the configured bar to what the pair can reach, and never raises it', () => {
      expect(effectiveNoveltyThreshold(RULE, ONE_EDIT, 0.8)).toBeCloseTo(0.6, 10);
      // A long pair can already clear 0.8, so the configured bar stands.
      const long = Array.from({ length: 60 }, (_, i) => `w${i}`).join(' ');
      expect(effectiveNoveltyThreshold(long, long, 0.8)).toBe(0.8);
      // An operator who set a bar BELOW the ceiling keeps their bar.
      expect(effectiveNoveltyThreshold(RULE, ONE_EDIT, 0.4)).toBe(0.4);
    });

    it('takes the shorter statement, whose shingles are the scarce ones', () => {
      expect(effectiveNoveltyThreshold(RULE, CONTAINED, 0.8)).toBeCloseTo(
        oneWordEditCeiling(wordCount(CONTAINED)) as number,
        10,
      );
    });

    it('leaves a pair the metric cannot judge at the configured threshold', () => {
      expect(effectiveNoveltyThreshold('lockfiles are regenerated by the queue', RULE, 0.8)).toBe(
        0.8,
      );
    });
  });

  describe('checkNovelty', () => {
    it('rejects the one-word edit that the fixed 0.8 bar waved through', () => {
      const fixed = checkNovelty(ONE_EDIT, [RULE], 0.8, 3, false);
      expect(fixed.mostSimilar?.score).toBeCloseTo(0.6, 10);
      expect(fixed.mostSimilar?.threshold).toBe(0.8);
      expect(fixed.novel).toBe(true); // the hole P9-35 (a) names

      const aware = checkNovelty(ONE_EDIT, [RULE], 0.8);
      expect(aware.novel).toBe(false);
      expect(aware.mostSimilar?.threshold).toBeCloseTo(0.6, 10);
    });

    it('still calls a two-word rewrite novel -- the rule is calibrated to one edit', () => {
      const twoEdits = RULE.replace('loop bound', 'iteration limit');
      expect(checkNovelty(twoEdits, [RULE], 0.8).novel).toBe(true);
    });

    it('leaves a six-word pair to the configured threshold', () => {
      const short = 'lockfiles are regenerated by the queue';
      const edited = 'lockfiles are regenerated by the worker';
      expect(oneWordEditCeiling(wordCount(short))).toBeNull();
      const result = checkNovelty(edited, [short], 0.8);
      expect(result.mostSimilar?.threshold).toBe(0.8);
      expect(result.novel).toBe(true);
    });

    it('reports the match that decided the verdict, not the highest raw score', () => {
      // CONTAINED is a shorter rule the candidate swallows whole: a lower raw
      // score than ONE_EDIT, but measured against a bar its own length can
      // reach, it is the redundancy that actually sinks the candidate.
      const fixed = checkNovelty(RULE, [ONE_EDIT, CONTAINED], 0.8, 3, false);
      expect(fixed.mostSimilar?.statement).toBe(ONE_EDIT);
      expect(fixed.novel).toBe(true);

      const aware = checkNovelty(RULE, [ONE_EDIT, CONTAINED], 0.8);
      expect(aware.novel).toBe(false);
      expect(aware.mostSimilar?.statement).toBe(CONTAINED);
      expect(aware.mostSimilar?.threshold).toBeCloseTo(0.4, 10);
    });

    it('keeps the polarity escape: a one-word flip stays novel for a human to judge', () => {
      const positive =
        'always retry the request automatically on a network timeout before giving up';
      const negative = positive.replace('always', 'never');
      const result = checkNovelty(negative, [positive], 0.8);
      expect(result.mostSimilar?.score).toBeGreaterThanOrEqual(
        result.mostSimilar?.threshold as number,
      );
      expect(result.polarityConflict).toBe(true);
      expect(result.novel).toBe(true);
    });

    it('is a no-op on an empty corpus, which has no length to be aware of', () => {
      expect(checkNovelty(RULE, [], 0.8).mostSimilar).toBeNull();
      expect(checkNovelty(RULE, [], 0.8).novel).toBe(true);
    });
  });
});

